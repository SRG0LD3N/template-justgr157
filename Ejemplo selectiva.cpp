// Ejemplo de Sentencia IF

#include <iostream>
using namespace std;

int num;

int main()
{

    cout << "Ingrese un numero: ";
    cin >> num;

    if (num == 5) {
        cout << "El valor que obtiene num es cinco";
    } else {
        cout << "El valor que obtiene num no es cinco";
    }

    return 0;
}

